use crate::hal::Display;

// ─── Public API ───────────────────────────────────────────────────────────────

/// Return the 5-byte column bitmap for an ASCII character.
#[inline]
pub fn glyph_columns(ascii: u8) -> &'static [u8; GLYPH_WIDTH] {
    if ascii >= GLYPH_FIRST && ascii <= GLYPH_LAST {
        &FONT5X7[(ascii - GLYPH_FIRST) as usize]
    } else {
        &REPLACEMENT_GLYPH
    }
}

/// Render a text string into a framebuffer page (one 8-pixel-tall stripe).
pub fn render_text<D: Display>(fb: &mut D::Buffer, page: usize, start_col: usize, text: &[u8]) {
    if page >= D::HEIGHT / 8 {
        return;
    }

    let mut col = start_col;
    for &ascii in text {
        if col + GLYPH_WIDTH > D::WIDTH {
            break;
        }

        let columns = glyph_columns(ascii);
        let page_offset = page * D::WIDTH;

        for (i, &col_byte) in columns.iter().enumerate() {
            fb.as_mut()[page_offset + col + i] = col_byte;
        }
        if col + GLYPH_WIDTH < D::WIDTH {
            fb.as_mut()[page_offset + col + GLYPH_WIDTH] = 0x00;
        }
        col += CHAR_ADVANCE;
    }
}

/// Clear one full page in the framebuffer to black (all pixels off).
pub fn clear_page<D: Display>(fb: &mut D::Buffer, page: usize) {
    let start = page * D::WIDTH;
    for byte in &mut fb.as_mut()[start..start + D::WIDTH] {
        *byte = 0;
    }
}
